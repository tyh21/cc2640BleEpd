const uint8_t *epd_font_get_ascii_bitmap(char ch)
{
    // Header: [first_char, width, height, count] = 4 bytes
    uint8_t first = EPD_ASCII_11X16[0];
    uint8_t count = EPD_ASCII_11X16[3];
    
    if (ch < first || ch >= first + count) return 0;
    
    return &EPD_ASCII_11X16[4 + (ch - first) * ASCII_FONT_BYTES];
}

const uint8_t *epd_font_get_cn_bitmap(uint16_t unicode)
{
    // Header: 4 bytes [0, width, height, count]
    uint8_t count = EPD_FontUTF8_16x16[3];
    
    // Each entry: 3 bytes Unicode index + 32 bytes bitmap = 35 bytes
    uint16_t offset = 4; // skip header
    uint8_t i;
    for (i = 0; i < count; i++) {
        uint16_t entry_unicode = ((uint16_t)EPD_FontUTF8_16x16[offset] << 8)
                               | EPD_FontUTF8_16x16[offset + 1];
        entry_unicode <<= 8;
        entry_unicode |= EPD_FontUTF8_16x16[offset + 2];
        
        // Unicode stored as 3 bytes: high, mid, low
        // Actually the format is: 0x00, 0xHH, 0xLL where HH:LL form a 16-bit code
        // Let's re-read: the 3 bytes are page, hi, lo of Unicode
        // Looking at the data: 0x00, 0x66, 0x1F for 星 (U+661F)
        // So bytes are: [0x00, 0x66, 0x1F] → Unicode = (0x66 << 8) | 0x1F = 0x661F
        uint16_t char_unicode = ((uint16_t)EPD_FontUTF8_16x16[offset + 1] << 8)
                              | EPD_FontUTF8_16x16[offset + 2];
        
        if (char_unicode == unicode) {
            return &EPD_FontUTF8_16x16[offset + 3];
        }
        offset += 3 + CN_FONT_BYTES;
    }
    return 0;
}
